package routers

import (
	beego "github.com/beego/beego/v2/server/web"
	"github.com/beego/beego/v2/server/web/context/param"
)

func init() {

    beego.GlobalControllerRouter["Beego_API/controllers:PropertyController"] = append(beego.GlobalControllerRouter["Beego_API/controllers:PropertyController"],
        beego.ControllerComments{
            Method: "Get",
            Router: `/`,
            AllowHTTPMethods: []string{"get"},
            MethodParams: param.Make(),
            Filters: nil,
            Params: nil})

    beego.GlobalControllerRouter["Beego_API/controllers:PropertyController"] = append(beego.GlobalControllerRouter["Beego_API/controllers:PropertyController"],
        beego.ControllerComments{
            Method: "GetByID",
            Router: `/:id`,
            AllowHTTPMethods: []string{"get"},
            MethodParams: param.Make(),
            Filters: nil,
            Params: nil})

}
